package mx.tecmilenio.svcobranza.db;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.SecureRandom;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

import mx.tecmilenio.svcobranza.AppException;

/**
 * Acceso a la base de datos H2 embebida. La aplicacion es de un solo usuario,
 * por lo que se usa una unica conexion.
 */
public final class Database implements AutoCloseable {

    private static final String USUARIO = "sv";
    private static final String CLAVE_MEMORIA = "pruebas";

    static final List<String> CATEGORIAS_INGRESO = List.of(
            "Nuevo ingreso", "Pago semanal o mensual", "Tiendita", "Experiencia",
            "Consulta médica o psicológica", "Otros");
    static final List<String> CATEGORIAS_EGRESO = List.of(
            "Nóminas", "Renta", "Luz", "Internet", "Abasto", "Otros");

    private static final String[] ESQUEMA = {
        "CREATE TABLE IF NOT EXISTS usuario_atendido ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "nombre VARCHAR(120) NOT NULL UNIQUE)",
        "CREATE TABLE IF NOT EXISTS categoria ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "tipo VARCHAR(10) NOT NULL, "
            + "nombre VARCHAR(60) NOT NULL, "
            + "UNIQUE (tipo, nombre))",
        "CREATE TABLE IF NOT EXISTS movimiento ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "tipo VARCHAR(10) NOT NULL, "
            + "fecha DATE NOT NULL, "
            + "monto DECIMAL(12,2) NOT NULL, "
            + "concepto VARCHAR(200) NOT NULL, "
            + "categoria VARCHAR(60) NOT NULL, "
            + "usuario_id BIGINT REFERENCES usuario_atendido(id), "
            + "forma_pago VARCHAR(20), "
            + "proveedor VARCHAR(120), "
            + "cancelado BOOLEAN DEFAULT FALSE NOT NULL)",
        "CREATE TABLE IF NOT EXISTS pendiente ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "tipo VARCHAR(15) NOT NULL, "
            + "fecha_limite DATE NOT NULL, "
            + "monto DECIMAL(12,2) NOT NULL, "
            + "concepto VARCHAR(200) NOT NULL, "
            + "categoria VARCHAR(60) NOT NULL, "
            + "contraparte VARCHAR(120) NOT NULL, "
            + "pagado BOOLEAN DEFAULT FALSE NOT NULL, "
            + "movimiento_id BIGINT REFERENCES movimiento(id))",
        "CREATE TABLE IF NOT EXISTS bitacora ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "fecha_hora TIMESTAMP NOT NULL, "
            + "tipo VARCHAR(20) NOT NULL, "
            + "accion VARCHAR(20) NOT NULL, "
            + "monto DECIMAL(12,2), "
            + "detalle VARCHAR(400))"
    };

    /** Operacion que se ejecuta dentro de una transaccion. */
    @FunctionalInterface
    public interface Operacion<T> {
        T ejecutar() throws SQLException;
    }

    private final Connection conexion;
    private boolean enTransaccion;

    private Database(String url, String clave) {
        try {
            this.conexion = DriverManager.getConnection(url, USUARIO, clave);
            crearEsquema();
        } catch (SQLException e) {
            throw new AppException("No se pudo abrir la base de datos: " + e.getMessage(), e);
        }
    }

    /**
     * Base de datos local cifrada con AES en la carpeta indicada. La clave se genera al azar
     * la primera vez y se guarda en la misma carpeta (archivo clave.key), para que no quede
     * escrita en el codigo publico.
     */
    public static Database local(Path carpeta) {
        try {
            Files.createDirectories(carpeta);
            String clave = leerOCrearClave(carpeta.resolve("clave.key"));
            String ruta = carpeta.toAbsolutePath().resolve("svcobranza").toString().replace('\\', '/');
            // H2 espera "claveArchivo claveUsuario" separadas por un espacio
            return new Database("jdbc:h2:file:" + ruta + ";CIPHER=AES", clave + " " + clave);
        } catch (IOException e) {
            throw new AppException("No se pudo preparar la carpeta de datos: " + carpeta, e);
        }
    }

    /** Base de datos en memoria, para pruebas. */
    public static Database enMemoria(String nombre) {
        return new Database("jdbc:h2:mem:" + nombre + ";DB_CLOSE_DELAY=-1", CLAVE_MEMORIA);
    }

    private static String leerOCrearClave(Path archivo) throws IOException {
        if (Files.exists(archivo)) {
            return Files.readString(archivo, StandardCharsets.UTF_8).trim();
        }
        byte[] azar = new byte[16];
        new SecureRandom().nextBytes(azar);
        StringBuilder hex = new StringBuilder();
        for (byte b : azar) {
            hex.append(String.format("%02x", b));
        }
        Files.writeString(archivo, hex.toString(), StandardCharsets.UTF_8);
        return hex.toString();
    }

    public Connection conexion() {
        return conexion;
    }

    /**
     * Ejecuta la operacion en una transaccion. Si ya hay una en curso, se une a ella.
     */
    public <T> T transaccion(Operacion<T> operacion) {
        if (enTransaccion) {
            try {
                return operacion.ejecutar();
            } catch (SQLException e) {
                throw new AppException("Error de base de datos: " + e.getMessage(), e);
            }
        }
        try {
            conexion.setAutoCommit(false);
            enTransaccion = true;
            T resultado = operacion.ejecutar();
            conexion.commit();
            return resultado;
        } catch (SQLException | RuntimeException e) {
            try {
                conexion.rollback();
            } catch (SQLException ignorada) {
                // la conexion ya fallo; se informa el error original
            }
            if (e instanceof RuntimeException) {
                throw (RuntimeException) e;
            }
            throw new AppException("Error de base de datos: " + e.getMessage(), e);
        } finally {
            enTransaccion = false;
            try {
                conexion.setAutoCommit(true);
            } catch (SQLException ignorada) {
                // sin accion
            }
        }
    }

    private void crearEsquema() throws SQLException {
        try (Statement st = conexion.createStatement()) {
            for (String sql : ESQUEMA) {
                st.execute(sql);
            }
        }
        sembrarCategorias("INGRESO", CATEGORIAS_INGRESO);
        sembrarCategorias("EGRESO", CATEGORIAS_EGRESO);
    }

    private void sembrarCategorias(String tipo, List<String> nombres) throws SQLException {
        String sql = "MERGE INTO categoria (tipo, nombre) KEY (tipo, nombre) VALUES (?, ?)";
        try (PreparedStatement ps = conexion.prepareStatement(sql)) {
            for (String nombre : nombres) {
                ps.setString(1, tipo);
                ps.setString(2, nombre);
                ps.executeUpdate();
            }
        }
    }

    @Override
    public void close() {
        try {
            conexion.close();
        } catch (SQLException e) {
            throw new AppException("No se pudo cerrar la base de datos", e);
        }
    }
}
